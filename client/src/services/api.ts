    const origin = String(params.origin || 'DEL').toUpperCase();
    const destination = String(params.destination || 'GOI').toUpperCase();
    const passengers = Number(params.passengers) || 1;
    const cabinClass = String(params.cabinClass || 'ECONOMY').toUpperCase() as
      | 'ECONOMY'
      | 'PREMIUM_ECONOMY'
      | 'BUSINESS'
      | 'FIRST';

    // Cabin class pricing multiplier:
    // Economy = 1.0x (base price ~₹4,000 - ₹6,000)
    // Premium Economy = 1.6x (approx ₹6,500 - ₹9,900)
    // Business = 2.8x (approx ₹11,500 - ₹17,500)
    // First Class = 4.5x (approx ₹18,000 - ₹28,000)
    const cabinMultiplier =
      cabinClass === 'BUSINESS'
        ? 2.8
        : cabinClass === 'PREMIUM_ECONOMY'
        ? 1.6
        : cabinClass === 'FIRST'
        ? 4.5
        : 1.0;

    // Filter or tailor flights for requested sector with accurate class pricing
    const sectorFlights = DEFAULT_FLIGHTS.map((f, i) => {
      const basePrices = [4899, 5499, 4499, 6199, 5199, 4199, 4399, 3999];
      const basePrice = basePrices[i % basePrices.length];
      const singleFare = Math.round(basePrice * cabinMultiplier);
      const totalFare = singleFare * passengers;

      return {
        ...f,
        id: `flight-${f.flightNumber.toLowerCase()}-${origin}-${destination}-${cabinClass.toLowerCase()}`,
        origin,
        destination,
        price: totalFare,
        cabinClass,
      };
    });

    const query = new URLSearchParams(params as Record<string, string>).toString();
    return safeFetch<{ success: boolean; data: FlightItem[] }>(`/flights/search?${query}`, {
      success: true,
      data: sectorFlights,
    });
